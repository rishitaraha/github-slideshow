# Handle Integrity in model error.
def handle_integrity_error(exc, context, response):
    response_data = {
        "message": ApiErrors.FORM_VALIDATION_ERROR.value.message,
        "slug": ApiErrors.FORM_VALIDATION_ERROR.value.slug,
        "details": {
            "form": {
                "message": ApiErrors.OBJECT_ALREADY_EXISTS.value.message,
                "slug": ApiErrors.OBJECT_ALREADY_EXISTS.value.slug,
            }
        },
        "type": exc.__class__.__name__,
    }
    return Response(response_data, status=status.HTTP_400_BAD_REQUEST)


# Error handling for validation errors.
def handle_validation_error(exc, context, response):
    exception_argument = exc.args[0]
    # Handle if response is None.
    if not response and exception_argument:
        message_slug = slugify(str(exception_argument))
        message = SlugMessageMaps.get(message_slug, exception_argument)
        response_data = {
            "message": message,
            "slug": message_slug,
            "type": exc.__class__.__name__,
        }

    # Handle Model generated errors.
    elif isinstance(exception_argument, ApiError):
        response_data = {
            "message": exception_argument.message,
            "slug": exception_argument.slug,
            "type": exc.__class__.__name__,
        }

    # Assumes there is only one non_field_error.
    elif isinstance(exception_argument, dict) and exception_argument.get(
        "non_field_errors"
    ):
        non_field_error = exception_argument.get("non_field_errors")
        if len(non_field_error) == 1:
            message = non_field_error[0]
            if is_json_string(message):
                api_error = json.loads(message)
                response_data = {
                    "message": api_error.get("message"),
                    "slug": api_error.get("slug"),
                    "type": exc.__class__.__name__,
                    "details": {
                        "form": {
                            "message": api_error.get("message"),
                            "slug": api_error.get("slug"),
                        },
                    },
                }
            else:
                message_slug = slugify(message)
                response_data = {
                    "message": ApiErrors.FORM_VALIDATION_ERROR.value.message,
                    "slug": ApiErrors.FORM_VALIDATION_ERROR.value.slug,
                    "type": exc.__class__.__name__,
                    "details": {
                        "form": {
                            "message": SlugMessageMaps.get(message_slug, message),
                            "slug": message_slug,
                        },
                    },
                }
    else:
        details = defaultdict(list)
        # Converting a dictionary with lists of exceptions into a list of lists of exceptions.
        error_list = (
            [
                exception
                for exception_dict in exception_argument
                for exception in exception_dict.items()
            ]
            if isinstance(exception_argument, list)
            else exception_argument.items()
        )
        for field, error_details in error_list:
            for detail in map(str, error_details):
                # Convert string to json if slug exist in as string dict.
                if "slug" in detail:
                    details[field].append(json.loads(detail))
                else:
                    message_slug = slugify(detail)
                    message = SlugMessageMaps.get(message_slug, detail)
                    details[field].append(
                        {
                            "message": message,
                            "slug": message_slug,
                        }
                    )
        response_data = {
            "message": ApiErrors.FORM_VALIDATION_ERROR.value.message,
            "slug": ApiErrors.FORM_VALIDATION_ERROR.value.slug,
            "type": exc.__class__.__name__,
            "details": dict(details),
        }
    return Response(response_data, status=status.HTTP_400_BAD_REQUEST)


