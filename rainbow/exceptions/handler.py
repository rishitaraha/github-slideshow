import json
from collections import defaultdict

from django.urls import reverse
from rest_framework import status
from rest_framework.response import Response
from rest_framework.views import exception_handler

from rainbow import logger
from shared.exception_handling import ApiError, ApiErrors, SlugMessageMaps
from shared.helpers import slugify

from .helpers import is_json_string


def custom_exception_handler(exc, context):
    exception_class = exc.__class__.__name__
    response = exception_handler(exc, context)
    if exception_class in handlers:
        return handlers[exception_class](exc, context, response)
    else:
        return handle_generic_error(exc, context, response)


# Generic Error Handler.
def handle_generic_error(exc, context, response):
    exception_argument = exc.args[0] if exc.args else ""
    # Handle if the exception is self generated.
    if isinstance(exception_argument, ApiError):
        # Assumes there is only one exception_argument for generic error.
        message = exception_argument.message
        message_slug = exception_argument.slug
        response_status = (
            response.status_code
            if hasattr(response, "status_code")
            else status.HTTP_400_BAD_REQUEST
        )

    # Handle the uncaught exceptions.
    elif not response:
        message_slug = ApiErrors.INTERNAL_SERVER_ERROR.value.slug
        message = ApiErrors.INTERNAL_SERVER_ERROR.value.message
        response_status = status.HTTP_500_INTERNAL_SERVER_ERROR
        # Logging data for internal error on console.
        logger.exception(str(exception_argument))

    # Handle when the error is of response type and  generated by django.
    else:
        detail = str(exception_argument)
        message_slug = slugify(detail)
        message = SlugMessageMaps.get(message_slug, detail)
        response_status = response.status_code

    response_data = {
        "message": message,
        "slug": message_slug,
        "type": exc.__class__.__name__,
    }

    return Response(response_data, status=response_status)


# Error handling for token errors.
def handle_token_error(exc, context, response):
    # If request is to refresh token for a user.
    if context["request"].get_full_path() == reverse("token-refresh"):
        response_data = {
            "message": ApiErrors.TOKEN_EXPIRED.value.message,
            "slug": ApiErrors.TOKEN_EXPIRED.value.slug,
            "type": "TokenBlacklisted",
        }
        return Response(response_data, status=status.HTTP_401_UNAUTHORIZED)

    response_data = {
        "message": ApiErrors.TOKEN_ERROR.value.message,
        "slug": ApiErrors.TOKEN_ERROR.value.slug,
        "type": exc.__class__.__name__,
    }

    return Response(response_data, status=status.HTTP_401_UNAUTHORIZED)


