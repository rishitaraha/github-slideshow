# To handle exception from a microservice.
def handle_microservice_exception(exc, context, response):
    microservice_response = exc.args[0]
    status_code = exc.status_code

    if (
        microservice_response.get("data") is not None
        and microservice_response.get("meta") is not None
    ):
        return Response(
            {
                "data": microservice_response["data"],
                "meta": microservice_response["meta"],
            },
            status=microservice_response["meta"]["status_code"],
        )
    else:
        return Response(
            {
                "data": microservice_response.pop("data", {}),
                "meta": {
                    "success": "false",
                    "status_code": exc.status_code,
                    "message": microservice_response,
                    "slug": microservice_response.pop("slug", ""),
                    "type": microservice_response.pop("type", ""),
                    "details": microservice_response.pop("details", {}),
                },
            },
            status=status_code,
        )


handlers = {
    "InvalidToken": handle_token_error,
    "NotAuthenticated": handle_unauthenticated_error,
    "PermissionDenied": handle_permission_error,
    "TokenError": handle_token_error,
    "ValidationError": handle_validation_error,
    "IntegrityError": handle_integrity_error,
    "MethodNotAllowed": handle_method_not_allowed,
    "MicroserviceException": handle_microservice_exception,
}
